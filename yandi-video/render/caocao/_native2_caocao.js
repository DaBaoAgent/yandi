// 展平whisper成单字
const chars=[];
for(const x of w){
  const t=x.text.replace(/[，。？！、,.\?!]/g,'');
  for(const ch of t) chars.push({ch, s:x.start, e:x.end});
}

// 按小停顿切句：词间停顿>0.14s 且累计>=4字 就切；单句<=22字
const segs=[];
let cur=[chars[0]];
for(let i=1;i<chars.length;i++){
  const gap=chars[i].s - chars[i-1].e;
  const len=cur.length;
  if((gap>0.14 && len>=4) || len>=22){ segs.push(cur); cur=[chars[i]]; }
  else cur.push(chars[i]);
}
segs.push(cur);

// 生成字幕
const subs=[];
for(const seg of segs){
  const t0=seg[0].s, t1=seg[seg.length-1].e;
  let txt=seg.map(x=>x.ch).join('');
  // 繁转简
  txt=txt.split('').map(ch=>S2T[ch]||ch).join('');
  // 错字修正
  for(const [bad,good] of FIX) txt=txt.split(bad).join(good);
  if(txt.length>=2 && txt.length<=22) subs.push([+t0.toFixed(2),+t1.toFixed(2),txt]);
}
fs.writeFileSync(__dirname+'/subs_native2.json',JSON.stringify(subs,null,1));
